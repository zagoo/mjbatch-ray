"""Generate docs/reference/configuration.md and docs/reference/run-config.schema.json
from the configuration models and validator, so the reference cannot drift.

  python tools/gen_config_reference.py [--check]

--check exits 1 if the checked-in files differ from what would be generated (CI).
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
import typing
from pathlib import Path

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
OUT_MD = ROOT / "docs/reference/configuration.md"
OUT_SCHEMA = ROOT / "docs/reference/run-config.schema.json"


def _type(ann) -> str:
  text = repr(ann).replace("typing.", "").replace("raysimbatch.config.models.", "")
  text = text.replace("<class '", "").replace("'>", "")
  for noise in ("Annotated[", ", Strict()", ", FieldInfo(annotation=NoneType, required=True, metadata=[Ge(ge=0)])"):
    text = text.replace(noise, "")
  return text


def _default(field) -> str:
  if field.is_required():
    return "*required*"
  v = field.default
  if isinstance(v, BaseModel):
    return "(section defaults)"
  if isinstance(v, str):
    return f'`"{v}"`'
  return f"`{json.dumps(v, default=str)}`" if not isinstance(v, tuple) else f"`{json.dumps(list(v), default=str)}`"


def _constraints(field) -> str:
  parts = []
  for m in field.metadata:
    for attr, sym in (("ge", "≥"), ("gt", ">"), ("le", "≤"), ("lt", "<"), ("min_length", "len≥"),
                      ("max_length", "len≤")):
      v = getattr(m, attr, None)
      if v is not None:
        parts.append(f"{sym}{v}")
  return ", ".join(parts)


def _section(model: type[BaseModel], path: str, out: list[str], seen: set) -> None:
  if model in seen and path:
    return
  seen.add(model)
  rows, nested = [], []
  for name, f in model.model_fields.items():
    ann = f.annotation
    sub = next((a for a in (typing.get_args(ann) or (ann,)) if isinstance(a, type) and issubclass(a, BaseModel)), None)
    rows.append(f"| `{name}` | {_type(ann)} | {_default(f)} | {_constraints(f)} |")
    if sub is not None:
      nested.append((f"{path}.{name}" if path else name, sub))
  out += [f"### `{path or 'RunConfig'}` ({model.__name__})", "", "| Field | Type | Default | Constraints |",
          "|---|---|---|---|", *rows, ""]
  for p, m in nested:
    _section(m, p, out, seen)


def _validation_codes() -> list[tuple[str, str, str, str]]:
  """(path, code, message, severity) literals from ConfigurationSystem.validate."""
  src = (ROOT / "src/raysimbatch/config/system.py").read_text()
  out = []
  for node in ast.walk(ast.parse(src)):
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "err" and len(node.args) >= 3:
      path, code, msg = (ast.unparse(a) for a in node.args[:3])
      sev = ast.unparse(node.args[3]) if len(node.args) > 3 else "'error'"
      out.append((path.strip("'\""), code.strip("'\""), msg.strip("'\"").removeprefix("f'").removeprefix('f"'),
                  sev.strip("'\"")))
  return out


def generate() -> tuple[str, str]:
  from raysimbatch.config import ConfigurationSystem
  from raysimbatch.config.models import RunConfig

  lines = ["# Configuration reference", "",
           "*Generated by `tools/gen_config_reference.py` from `src/raysimbatch/config/models.py` and "
           "`config/system.py`. Do not edit by hand.*", "",
           "Configuration is strict: unknown keys, wrong types and out-of-range values are rejected with the "
           "offending dotted path, and all independent errors are reported together. YAML is an input format only "
           "(no interpolation). Environment variables never change semantic configuration. The canonical hash "
           "covers the resolved form (defaults applied, weights normalized).", "",
           "The JSON Schema is in [run-config.schema.json](run-config.schema.json). Validate a file with:", "",
           "```bash", "raysimbatch config validate --config my-run.yaml", "```", "",
           "## Fields", ""]
  _section(RunConfig, "", lines, set())
  lines += ["## Cross-field validation rules", "",
            "Reported by `raysimbatch config validate` and at submission. `warning` entries do not block.", "",
            "| Path | Code | Rule | Severity |", "|---|---|---|---|"]
  for path, code, msg, sev in _validation_codes():
    lines.append(f"| `{path}` | `{code}` | {msg.replace('|', '/')} | {sev} |")
  lines += ["", "## Change classification", "",
            "`raysimbatch config diff --config old.yaml --new new.yaml` classifies each changed path:", "",
            "- **hot**: applied to a running run (telemetry level, sampling, OTLP endpoint);",
            "- **boundary**: applied at the next wave or episode boundary (curriculum, target sizes, flow "
            "reductions, node bounds, policy version);",
            "- **new_run**: requires a new run (everything else; a resume with such a change is refused);",
            "- **forbidden**: never allowed inside a run (task retries, loosening health or parity bounds, "
            "disabling gates, changing `run_id`).", ""]
  schema = json.dumps(ConfigurationSystem().json_schema(), indent=2, sort_keys=True) + "\n"
  return "\n".join(lines) + "\n", schema


def main(argv=None) -> int:
  ap = argparse.ArgumentParser()
  ap.add_argument("--check", action="store_true")
  args = ap.parse_args(argv)
  md, schema = generate()
  if args.check:
    stale = [p for p, text in ((OUT_MD, md), (OUT_SCHEMA, schema)) if not p.exists() or p.read_text() != text]
    for p in stale:
      print(f"stale: {p.relative_to(ROOT)} (run tools/gen_config_reference.py)")
    return 1 if stale else 0
  OUT_MD.parent.mkdir(parents=True, exist_ok=True)
  OUT_MD.write_text(md)
  OUT_SCHEMA.write_text(schema)
  print(f"wrote {OUT_MD.relative_to(ROOT)} and {OUT_SCHEMA.relative_to(ROOT)}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
