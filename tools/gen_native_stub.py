"""Regenerate src/raysimbatch/_native.pyi, the type stub of the compiled native module.

Pyright resolves `raysimbatch` in src/, where the built extension does not live, so it saw
nothing behind `raysimbatch._native`. The stub is generated from the built module by
nanobind's stubgen, the same nanobind version as the build. Rerun after changing
native/src/module.cpp (tests/tooling/test_native_stub.py fails until then):

  uv run --with nanobind==3.1.0 python tools/gen_native_stub.py
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "raysimbatch" / "_native.pyi"
HEADER = "# Generated by tools/gen_native_stub.py (nanobind.stubgen {v}) from the built module; do not edit.\n"


def main() -> int:
  pinned = re.search(r'"nanobind==([^"]+)"', (ROOT / "pyproject.toml").read_text()).group(1)
  if version("nanobind") != pinned:
    raise SystemExit(f"use nanobind=={pinned}, the build's version (see the module docstring)")
  with tempfile.TemporaryDirectory() as tmp:
    out = Path(tmp) / "_native.pyi"
    subprocess.run([sys.executable, "-m", "nanobind.stubgen", "-q", "-m", "raysimbatch._native", "-o", str(out)],
                   check=True)
    OUT.write_text(HEADER.format(v=pinned) + out.read_text())
  print(f"wrote {OUT.relative_to(ROOT)}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
