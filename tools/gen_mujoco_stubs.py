"""Regenerate typings/mujoco: type stubs for the installed MuJoCo's pybind11 bindings.

MuJoCo ships no stubs, so pyright saw nothing behind `mujoco.*` (155 errors in the
triage). The stubs are generated from the real extension modules, never written by hand.
Rerun after every MuJoCo upgrade (tests/tooling/test_mujoco_stubs.py fails until then):

  uv run --with pybind11-stubgen==3.0.0 python tools/gen_mujoco_stubs.py
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import mujoco

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "typings" / "mujoco"
STUBGEN = "3.0.0"
PROVENANCE = ROOT / "typings" / "README.md"


def main() -> int:
  from importlib.metadata import version

  if version("pybind11-stubgen") != STUBGEN:
    raise SystemExit(f"use pybind11-stubgen=={STUBGEN} (see the module docstring)")
  with tempfile.TemporaryDirectory() as tmp:
    subprocess.run([sys.executable, "-m", "pybind11_stubgen", "mujoco", "-o", tmp, "--numpy-array-use-type-var"],
                   check=True)
    shutil.rmtree(OUT, ignore_errors=True)
    shutil.copytree(Path(tmp) / "mujoco", OUT)
  PROVENANCE.write_text(
    "# Generated type stubs\n\n"
    "`mujoco/`: generated by `tools/gen_mujoco_stubs.py` from the installed MuJoCo's pybind11\n"
    "bindings (MuJoCo is Apache-2.0, Copyright DeepMind Technologies Limited). Do not edit\n"
    "by hand; regenerate after a MuJoCo upgrade.\n\n"
    f"generated-for: mujoco=={mujoco.__version__} pybind11-stubgen=={STUBGEN} platform={sys.platform}\n")
  print(f"wrote {OUT.relative_to(ROOT)} for mujoco {mujoco.__version__}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
